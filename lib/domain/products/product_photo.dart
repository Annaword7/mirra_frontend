/// Какое фото продукта показывать.
///
/// У скана два снимка: `image_url` — то, что сфотографировал пользователь
/// (кривой ракурс, своя кухня, свой свет), и `catalog_image_url` — каталожное,
/// ровное и одинаковое для всех. В списках (лента, косметичка, выбор «Из моих
/// продуктов») показываем каталожное: сетка из них выглядит как витрина, а не
/// как чужая фотопленка. Скан пользователя — запасной вариант, когда
/// каталожного фото не нашли.
///
/// На самой карточке продукта показываем оба: каталожное первым, свой скан
/// вторым (см. `_productPhotos` в itemcard2).
extension ProductPhoto on ImagesRow {
  /// Каталожное фото, иначе собственный скан (может быть пустой строкой).
  String get displayPhotoUrl {
    final catalog = catalogImageUrl;
    return (catalog != null && catalog.isNotEmpty) ? catalog : imageUrl;
  }
}
